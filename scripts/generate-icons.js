// Creates the static React Native asset map for the hand-authored PNG illustrations.
const fs = require('fs');
const path = require('path');

const root = path.join(__dirname, '..');
const iconsDir = path.join(root, 'assets', 'icons');
const names = fs
  .readdirSync(iconsDir)
  .filter((file) => file.endsWith('.png'))
  .map((file) => path.basename(file, '.png'))
  .sort();

if (names.length !== 147) {
  throw new Error(`Expected 147 PNG icons, found ${names.length}`);
}

const entries = names
  .map((name) => `  '${name}': require('../../assets/icons/${name}.png'),`)
  .join('\n');
const output =
  '// GENERATED by scripts/generate-icons.js. Do not edit by hand.\n' +
  "import type { ImageSourcePropType } from 'react-native';\n\n" +
  'export const ICON_IMAGES: Record<string, ImageSourcePropType> = {\n' +
  `${entries}\n` +
  '};\n';

fs.writeFileSync(path.join(root, 'lib', 'icons', 'icon-images.ts'), output);
console.log(`mapped ${names.length} PNG icons`);
